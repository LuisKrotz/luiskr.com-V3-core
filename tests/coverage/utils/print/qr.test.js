describe('print qr encoder', () => {
  test.each(GOLDENS.map((g) => [g.text.slice(0, 40), g]))(
    'encodes %s… to the segno reference matrix',
    (_label, g) => {
      const qr = encodeQr(g.text)

      expect(qr).not.toBeNull()
      expect(qr.size).toBe(g.size)

      const rows = []

      for (let y = 0; y < qr.size; y++) {
        let row = ''

        for (let x = 0; x < qr.size; x++) row += qr.modules[y * qr.size + x]

        rows.push(row)
      }

      expect(rows).toEqual(g.matrix)
    }
  )

  test('empty payload still encodes a valid v1 symbol', () => {
    const qr = encodeQr('')

    expect(qr).not.toBeNull()
    expect(qr.size).toBe(21)
    expect(qr.modules).toHaveLength(21 * 21)
  })

  test('payload past the v40-M capacity returns null', () => {
    expect(encodeQr('x'.repeat(3000))).toBeNull()
    expect(qrSvg('x'.repeat(3000))).toBeNull()
  })

  test('qrSvg emits a single-path svg with quiet-zone viewBox', () => {
    const text = 'https://luiskr.com/en/'
    const svg = qrSvg(text)
    const qr = encodeQr(text)

    expect(svg).not.toBeNull()
    expect(svg.tagName.toLowerCase()).toBe('svg')
    expect(svg.getAttribute('viewBox')).toBe(`0 0 ${qr.size + 8} ${qr.size + 8}`)
    expect(svg.getAttribute(ARIA_ATTRS.ARIA_HIDDEN)).toBe(ATTR_VALUES.TRUE)

    const path = svg.querySelector('path')

    expect(path).not.toBeNull()
    expect(path.getAttribute('d')).toContain('M')
    expect(path.getAttribute('fill')).toBe(ATTR_VALUES.CURRENT_COLOR)
  })

  test('qrSvg path dark module count matches the matrix', () => {
    const text = 'https://luiskr.com/en/metcha'
    const svg = qrSvg(text)
    const d = svg.querySelector('path').getAttribute('d')

    // Every painted run contributes h<w>v1 — total dark area = Σ run widths.
    const painted = [...d.matchAll(/h(\d+)v1/g)].reduce((n, m) => n + Number(m[1]), 0)

    const qr = encodeQr(text)
    const dark = qr.modules.reduce((n, v) => n + v, 0)

    expect(painted).toBe(dark)
  })
})
